import { test, expect } from "./fixtures";
import fs from "node:fs";
import path from "node:path";
test("customer MVP → draft recovery → save → source timeline → mock PPT", async ({ page, request }) => {
  const c = await (await request.post("/v1/cases", { data: { title: "MVP browser case" } })).json();
  const uploaded = await request.post("/v1/cases/" + c.id + "/evidence", { multipart: { file: { name: "chat-1.png", mimeType: "image/png", buffer: fs.readFileSync(path.resolve("../fixtures/demo_private_lending/chat-1.png")) } } });
  expect(uploaded.ok()).toBeTruthy();
  const evidence = await uploaded.json();
  const transcript = await request.post("/v1/cases/" + c.id + "/perception/runs", { data: { adapter: "manual", fixtures: { [evidence.id]: [{ text: "Visible timeline message", timestamp: null, bbox: [10, 10, 50, 50] }] } } });
  expect(transcript.ok()).toBeTruthy();
  await page.goto("/?case=" + c.id);
  await expect(page.getByRole("heading", { name: "概览", exact: true })).toBeVisible();
  const nav = page.getByRole("navigation");
  await expect(nav.getByRole("button", { name: /概览/ })).toBeVisible();
  await expect(nav.getByRole("button", { name: /编辑/ })).toBeVisible();
  await expect(nav.getByRole("button", { name: /证据时间线/ })).toBeVisible();
  await expect(nav.getByRole("button", { name: /生成 PPT/ })).toBeVisible();
  await expect(nav.getByRole("button", { name: /模型设置|证明矩阵|人工审核/ })).toHaveCount(0);
  await nav.getByRole("button", { name: /编辑/ }).click();
  await page.locator(".settings-form").getByLabel("工作备注", { exact: true }).fill("Draft survives reload");
  await page.reload();
  await expect(page.getByText("已恢复本机未保存的草稿。")).toBeVisible();
  await expect(page.locator(".settings-form").getByLabel("工作备注", { exact: true })).toHaveValue("Draft survives reload");
  await page.getByRole("button", { name: "保存", exact: true }).click();
  await expect(page.getByText("案件信息已保存。")).toBeVisible();
  await page.reload();
  await expect(page.locator(".settings-form").getByLabel("工作备注", { exact: true })).toHaveValue("Draft survives reload");
  await nav.getByRole("button", { name: /证据时间线/ }).click();
  await expect(page.getByText("Visible timeline message", { exact: true })).toHaveCount(0);
  const image = page.getByRole("img", { name: "chat-1.png", exact: true });
  await expect(image).toBeVisible();
  await expect.poll(() => image.evaluate(img => (img as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  await expect(page.locator(".image-timeline time").first()).toBeVisible();
  await expect(page.getByRole("link", { name: "查看原图", exact: true }).first()).toHaveAttribute("href", "/v1/cases/" + c.id + "/evidence/" + evidence.id + "/file");
  const popupPromise = page.waitForEvent("popup");
  await image.click();
  const original = await popupPromise;
  await original.waitForLoadState();
  expect(original.url()).toContain("/evidence/" + evidence.id + "/file");
  await expect(original.locator("img")).toBeVisible();
  await original.close();
  await page.screenshot({ path: "../artifacts/user-workbench-image-timeline-desktop.png", fullPage: true });
  await nav.getByRole("button", { name: /生成 PPT/ }).click();
  await page.getByRole("button", { name: "生成 PPT", exact: true }).click();
  await expect(page.getByText(/模拟完成，尚未生成 PPT 文件/)).toBeVisible();
  await page.screenshot({ path: "../artifacts/user-workbench-mvp-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await nav.getByRole("button", { name: /证据时间线/ }).click();
  await expect(page.getByRole("heading", { name: "证据时间线", exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: "../artifacts/user-workbench-mvp-mobile.png", fullPage: true });
});
