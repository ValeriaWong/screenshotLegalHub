import { test,expect,artifactPath } from "./fixtures";
import { execFileSync } from "node:child_process";
import path from "node:path";
test("case documents: mixed formats, durable PDF windows, drafts and source-page highlight",async({page,request})=>{
  test.setTimeout(150000);
  const fixtureRoot=path.join(process.env.E2E_DATA_DIR!,"document-fixtures");
  const parserPython=path.resolve("../.tools/mineru-env",process.platform==="win32" ? "Scripts/python.exe" : "bin/python");
  execFileSync(parserPython,[path.resolve("../scripts/make-document-fixtures.py"),fixtureRoot],{windowsHide:true});
  const cid=(await(await request.post("/v1/cases",{data:{title:"Document reading browser fixture"}})).json()).id;
  const root="/v1/cases/"+cid+"/documents";
  await page.goto("/?case="+cid);
  await page.getByRole("button",{name:"打开资料工作区",exact:true}).click();
  await page.getByLabel("添加资料（可多选）",{exact:true}).setInputFiles(["paper.pdf","notes.docx","table.xlsx"].map(name=>path.join(fixtureRoot,name)));
  await expect(page.getByText("已添加 3 / 3 份资料。",{exact:true})).toBeVisible();
  const docs=await(await request.get(root)).json();
  for(const name of ["notes.docx","table.xlsx"]){
    const row=docs.find((d:{filename:string})=>d.filename===name);
    const response=await request.post(root+"/"+row.id+"/parse-next",{data:{pages:3}});
    expect(response.ok()).toBeTruthy();expect((await response.json()).status).toBe("complete");
  }
  const pdf=docs.find((d:{filename:string})=>d.filename==="paper.pdf");
  await page.getByRole("combobox",{name:"选择资料",exact:true}).selectOption(pdf.id);
  const progress=page.getByRole("region",{name:"资料整理工作区"}).locator('span[role="status"]');
  await page.getByRole("button",{name:"解析下一段（最多 3 页）",exact:true}).click();
  await expect(progress).toContainText("已解析 3 / 7 页",{timeout:40000});
  await page.getByRole("textbox",{name:"本段分析 / 阅读批注",exact:true}).fill("本段金额已核对，待继续第 4 页");
  await expect(page.getByText("批注已缓存在本机，点击保存后同步服务器",{exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole("textbox",{name:"本段分析 / 阅读批注",exact:true})).toHaveValue("本段金额已核对，待继续第 4 页");
  await page.getByRole("button",{name:"保存批注与阅读位置",exact:true}).click();
  await expect(page.getByText("批注和阅读位置已保存",{exact:true})).toBeVisible();
  expect((await request.put(root+"/"+pdf.id+"/note",{data:{expected_revision:1,text:"协作审核的新批注",cursor:0}})).ok()).toBeTruthy();
  await page.getByRole("textbox",{name:"本段分析 / 阅读批注",exact:true}).fill("合并后的人工核对记录");
  await page.getByRole("button",{name:"保存批注与阅读位置",exact:true}).click();
  await expect(page.getByText(/批注已有新版本/)).toBeVisible();
  await page.getByRole("button",{name:"比对服务器批注",exact:true}).click();
  await expect(page.getByText("协作审核的新批注",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"使用该版本作为保存基线，保留当前文本",exact:true}).click();
  await expect(page.getByRole("textbox",{name:"本段分析 / 阅读批注",exact:true})).toHaveValue("合并后的人工核对记录");
  await page.getByRole("button",{name:"保存批注与阅读位置",exact:true}).click();
  await expect(page.getByText("批注和阅读位置已保存",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"解析下一段（最多 3 页）",exact:true}).click();
  await expect(progress).toContainText("已解析 6 / 7 页",{timeout:40000});
  await page.getByRole("button",{name:"解析下一段（最多 3 页）",exact:true}).click();
  await expect(progress).toContainText("已解析 7 / 7 页",{timeout:40000});
  await page.getByRole("button",{name:/定位原文 · 第 7 页/}).first().click();
  await expect(page.getByRole("complementary",{name:"原文位置与批注",exact:true})).toBeFocused();
  const image=page.getByRole("img",{name:"原文第 7 页",exact:true});
  await expect(image).toBeVisible();
  await expect.poll(()=>image.evaluate(img=>(img as HTMLImageElement).naturalWidth),{timeout:30000}).toBeGreaterThan(0);
  await expect(page.locator('svg[aria-label="当前原文高亮区域"] rect')).toHaveCount(1);
  await page.getByRole("combobox",{name:"原文缩放",exact:true}).selectOption("200");
  await page.getByRole("combobox",{name:"原文缩放",exact:true}).selectOption("100");
  await page.screenshot({path:artifactPath("documents-desktop.png"),fullPage:true});
  await page.setViewportSize({width:375,height:812});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await image.scrollIntoViewIfNeeded();
  await page.screenshot({path:artifactPath("documents-mobile.png"),fullPage:true});
  await page.setViewportSize({width:844,height:390});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  const final=await(await request.get(root+"/"+pdf.id)).json();
  expect(final.document.producer).toBe("4.0.12");
  expect([...new Set(final.items.map((b:{page:number})=>b.page))]).toEqual([1,2,3,4,5,6,7]);
  expect((await request.get(root+"/"+pdf.id+"/file")).ok()).toBeTruthy();
});
