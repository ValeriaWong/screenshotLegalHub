import { test,expect,artifactPath } from "./fixtures";
test("document publication, durable parsing, and independent versions keep old sources readable",async({page,request})=>{
  const cid=(await(await request.post("/v1/cases",{data:{title:"Versioned source browser fixture"}})).json()).id;
  const root="/v1/cases/"+cid+"/documents";
  const original="甲😀确认金额520元。".repeat(40);
  const doc=await(await request.post(root,{multipart:{file:{name:"versioned.txt",mimeType:"text/plain",buffer:Buffer.from(original)}}})).json();
  await page.goto("/?case="+cid+"&document="+doc.id);
  await page.getByRole("button",{name:"解析全部剩余页面",exact:true}).click();
  await page.reload();
  await expect(page.getByRole("region",{name:"资料整理工作区"}).locator('span[role="status"]').first()).toContainText("解析完成",{timeout:15000});
  await page.getByRole("button",{name:"发布此解析为案件来源",exact:true}).click();
  await expect(page.getByText("此解析快照已发布，原有版本保留",{exact:true})).toBeVisible();
  const sources=await(await request.get("/v1/cases/"+cid+"/source-refs")).json();
  const source=sources.find((r:{source_kind:string})=>r.source_kind==="document");
  expect(source).toBeTruthy();
  const typed=await request.get(root+"/"+doc.id+"/parse-run");
  expect(typed.ok()).toBeTruthy();expect((await typed.json()).quality_status).toBe("unreviewed");
  await page.getByText("解析版本与对照配置",{exact:true}).click();
  await page.getByLabel("文本分块字符数",{exact:true}).fill("200");
  await page.getByRole("button",{name:"创建独立解析版本",exact:true}).click();
  await expect.poll(()=>new URL(page.url()).searchParams.get("document")).not.toBe(doc.id);
  const second=new URL(page.url()).searchParams.get("document")!;
  await expect(page.getByRole("button",{name:"解析全部剩余页面",exact:true})).toBeEnabled();
  await page.getByRole("button",{name:"解析全部剩余页面",exact:true}).click();
  await expect(page.getByRole("button",{name:"发布此解析为案件来源",exact:true})).toBeVisible({timeout:15000});
  const resolved=await request.post("/v1/cases/"+cid+"/resolve-source",{data:{source_ref_id:source.id,quote:"金额520元"}});
  expect(resolved.ok()).toBeTruthy();
  expect((await resolved.json()).text_match).toBe("ambiguous");
  expect((await(await request.get(root+"/"+doc.id)).json()).items.length).toBeLessThan((await(await request.get(root+"/"+second)).json()).items.length);
  const search=await(await request.get("/v1/cases/"+cid+"/source-search?q="+encodeURIComponent("金额"))).json();
  expect(search.items.some((r:{document_id:string;published:boolean})=>r.document_id===doc.id && r.published)).toBeTruthy();
  expect(search.items.some((r:{document_id:string})=>r.document_id===second)).toBeFalsy();
  await page.screenshot({path:artifactPath("document-versions-desktop.png"),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:artifactPath("document-versions-mobile.png"),fullPage:true});
});
