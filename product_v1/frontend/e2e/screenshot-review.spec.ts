import fs from "node:fs";
import path from "node:path";
import { test, expect } from "./fixtures";
const report = path.resolve("../reports/screenshot-panel-2026-11-06");
test("lossless screenshot review, backup recovery, isolated locks and all workbench themes", async ({ page, request }) => {
  test.setTimeout(120000);
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("dialog", d => void d.accept());
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/review.html");
  await expect(page.getByRole("heading", { name: "数据审核台", exact: true })).toBeVisible();
  await expect(page.getByText("已完成 0 / 3 张", { exact: true })).toBeVisible();
  await expect(page.getByRole("img", { name: "a001 待审核聊天截图" })).toBeVisible();
  fs.mkdirSync(report, { recursive: true });
  await page.screenshot({ path: path.join(report, "review-desktop.png"), fullPage: true });
  await page.getByRole("button", { name: "放大 2×" }).click();
  await expect(page.getByRole("img", { name: "a001 待审核聊天截图" })).toHaveCSS("width", /[0-9.]+px/);
  await page.getByRole("button", { name: "还原 1×" }).click();
  for (let i = 0; i < 3; i++) {
    for (let m = 0; m < 2; m++) {
      await page.getByRole("group", { name: "当前消息判项", exact: true }).getByRole("button", { name: "内容对", exact: true }).click();
      await expect(page.getByText("消息已判 " + (i * 2 + m + 1) + " / 6", { exact: true })).toBeVisible();
    }
    await page.getByRole("group", { name: "整图判项", exact: true }).getByRole("button", { name: "通过", exact: true }).click();
    await page.getByRole("button", { name: "保存整图审核", exact: true }).click();
    await expect(page.getByText("已完成 " + (i + 1) + " / 3 张", { exact: true })).toBeVisible();
    if (i < 2) await page.getByRole("button", { name: "下一张 ›", exact: true }).click();
  }
  await page.getByRole("button", { name: "生成完整导出 JSON" }).click();
  const jsonText = await page.getByLabel("全量导出 JSON · review-A.json").inputValue();
  const backup = JSON.parse(jsonText);
  expect(backup.items[0].corrected_messages[0].message_bbox).toEqual(backup.items[0].original_messages[0].message_bbox);
  expect(backup.items[0].corrected_messages[0].custom).toEqual({ keep: "value" });
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "下载文件", exact: true }).click();
  const downloaded = await download;
  const downloadedPath = await downloaded.path();
  expect(fs.readFileSync(downloadedPath!, "utf8")).toBe(jsonText);
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.getByRole("button", { name: "复制全部", exact: true }).click();
  await expect.poll(async () => (await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n/g, "\n")).toBe(jsonText);

  await page.getByRole("button", { name: "清除此条审核", exact: true }).click();
  await expect(page.getByText("消息已判 5 / 6", { exact: true })).toBeVisible();
  await page.getByRole("group", { name: "整图判项", exact: true }).getByRole("button", { name: "需改", exact: true }).click();
  await page.getByLabel("整图批注", { exact: true }).fill("测试恢复前的草稿");
  await page.getByRole("button", { name: "保存整图审核", exact: true }).click();
  await page.getByText("从完整备份恢复", { exact: true }).click();
  await page.getByLabel("粘贴旧导出 JSON").fill('{"invalid":true}');
  await page.getByRole("button", { name: "验证并恢复当前数据集" }).click();
  await expect(page.getByText(/不是有效的本数据集导出 JSON/)).toBeVisible();
  expect((await (await request.get("/v1/review/screenshot-panels/A")).json()).counts.messages_reviewed).toBe(5);
  await page.getByLabel("粘贴旧导出 JSON").fill(jsonText);
  await page.getByRole("button", { name: "验证并恢复当前数据集" }).click();
  await expect(page.getByText("已完成 3 / 3 张", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText("消息已判 6 / 6", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "生成完整导出 JSON" }).click();
  await page.getByRole("button", { name: "锁定数据集 A", exact: true }).click();
  await expect(page.getByRole("button", { name: "数据集 A 已锁定", exact: true })).toBeDisabled();
  const locked = await (await request.get("/v1/review/screenshot-panels/A")).json();
  const rejected = await request.put("/v1/review/screenshot-panels/A/items/a001/messages/m1", { data: { expected_version: locked.version, review: null } });
  expect(rejected.status()).toBe(409);

  await page.getByRole("button", { name: "数据集 B 审核模拟生成" }).click();
  await expect(page.getByText("已完成 0 / 1 张", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "保存这条", exact: true })).toBeDisabled();
  await page.getByRole("group", { name: "当前消息判项", exact: true }).getByRole("button", { name: "内容对", exact: true }).click();
  await page.getByLabel("内容依据", { exact: true }).selectOption("synthetic_completion");
  await page.getByLabel("具体时间依据").selectOption("simulated");
  await page.getByLabel("说话人依据", { exact: true }).selectOption("simulated");
  await page.getByRole("button", { name: "保存这条", exact: true }).click();
  await expect(page.getByText("消息已判 1 / 2", { exact: true })).toBeVisible();
  await page.getByRole("group", { name: "当前消息判项", exact: true }).getByRole("button", { name: "多余一条", exact: true }).click();
  await expect(page.getByRole("button", { name: "保存这条", exact: true })).toBeDisabled();
  await page.getByLabel("内容依据", { exact: true }).selectOption("unsupported");
  await page.getByLabel("具体时间依据").selectOption("unknown");
  await page.getByLabel("说话人依据", { exact: true }).selectOption("unknown");
  await page.getByLabel("批注（必填）", { exact: true }).fill("来源未提供此回复，删除。");
  await page.getByRole("button", { name: "保存这条", exact: true }).click();
  await expect(page.getByText("消息已判 2 / 2", { exact: true })).toBeVisible();
  await page.getByRole("group", { name: "整图判项", exact: true }).getByRole("button", { name: "需重生成", exact: true }).click();
  await page.getByLabel("整图批注", { exact: true }).fill("删除无依据回复，保留合成性质。");
  await page.getByRole("button", { name: "根据已存批注生成指令草稿" }).click();
  await page.getByRole("button", { name: "保存整图审核", exact: true }).click();
  await expect(page.getByText("已完成 1 / 1 张", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "导出重生成包", exact: true }).click();
  const regenText = await page.getByLabel("全量导出 JSON · regen_jobs.json").inputValue();
  const regen = JSON.parse(regenText);
  expect(regen.synthetic).toBe(true);
  expect(regen.jobs[0].corrected_dialogue.map((m: {id:string}) => m.id)).toEqual(["m1"]);
  await page.setViewportSize({ width: 375, height: 812 });
  await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: path.join(report, "review-mobile-overview.png"), fullPage: true });
  await page.locator(".screenshot-current").evaluate(el => { el.scrollIntoView({ block: "start" }); window.scrollBy(0, -120); });
  await page.screenshot({ path: path.join(report, "review-mobile.png") });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(page.getByRole("button", { name: "快捷上一条" })).toBeVisible();
  await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" });
  await page.screenshot({ path: path.join(report, "review-dark.png") });
  await page.emulateMedia({ colorScheme: "light" });
  for (const url of ["/studio.html", "/evaluation.html", "/console.html"]) {
    await page.goto(url);
    await expect(page.locator("html")).toHaveAttribute("data-workbench-theme", "pack3");
    await expect(page.locator(url.includes("console") ? ".case-header" : ".research-title h1")).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await page.goto("/studio.html");
  await page.getByRole("button", { name: "从 B 修正包重生成" }).click();
  await expect(page.getByRole("heading", { name: "按 B 审核包重生成" })).toBeVisible();
  await page.getByLabel("重生成包 JSON", { exact: true }).fill(regenText);
  await page.getByRole("button", { name: "验证并预览输入包" }).click();
  const promptResponse = await request.post("/v1/studio/prompts", { data: { name: "修正包验证规则", markdown: "生成合成候选，原文支持与模拟分开标记。", note: "test", expected_version: 0, idempotency_key: crypto.randomUUID() } });
  expect(promptResponse.ok()).toBe(true);
  const prompt = await promptResponse.json();
  await page.reload();
  await page.getByRole("button", { name: "从 B 修正包重生成" }).click();
  await page.getByLabel("重生成包 JSON", { exact: true }).fill(regenText);
  await page.getByRole("button", { name: "验证并预览输入包" }).click();
  await page.getByRole("combobox", { name: "生成规则", exact: true }).selectOption(prompt.id);
  await page.getByLabel("批次名称", { exact: true }).fill("修正包离线验证");
  await page.getByRole("button", { name: "按此修正包生成待审样本" }).click();
  await expect(page.getByText("已创建待审合成批次。", { exact: false })).toBeVisible();
  await expect(page.getByRole("button", { name: "按此修正包生成待审样本" })).toBeEnabled();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: path.join(report, "studio-package-desktop.png"), fullPage: true });
  for (const [url, name] of [["/evaluation.html", "evaluation-desktop.png"], ["/console.html", "console-desktop.png"]]) {
    await page.goto(url);
    await expect(page.locator("html")).toHaveAttribute("data-workbench-theme", "pack3");
    await expect(page.locator(url.includes("console") ? ".case-header" : ".research-title h1")).toBeVisible();
    await page.screenshot({ path: path.join(report, name) });
  }
  await page.goto("/");
  await expect(page.locator("html")).not.toHaveAttribute("data-workbench-theme", "pack3");
  expect(errors).toEqual([]);
});
